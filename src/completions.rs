//! Zero-dependency shell completion script generator (`iris completions`).
//!
//! Introspects `crate::cli::cli_command()` at runtime so subcommands, flags,
//! and help descriptions stay synchronized across Bash, Zsh, Fish, and PowerShell.

use std::collections::BTreeSet;
use std::fmt::Write as _;

/// Supported target shells for `iris completions <shell>`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShellKind {
    Bash,
    Zsh,
    Fish,
    PowerShell,
}

impl ShellKind {
    pub fn parse(raw: &str) -> Result<Self, String> {
        match raw.trim().to_ascii_lowercase().as_str() {
            "bash" => Ok(Self::Bash),
            "zsh" => Ok(Self::Zsh),
            "fish" => Ok(Self::Fish),
            "powershell" | "pwsh" | "ps1" => Ok(Self::PowerShell),
            other => Err(format!(
                "unsupported shell `{other}` (expected: bash, zsh, fish, powershell)"
            )),
        }
    }
}

struct OptSpec {
    short: Option<char>,
    long: Option<String>,
    about: String,
}

struct CmdSpec {
    name: String,
    about: String,
    opts: Vec<OptSpec>,
    pos_values: Vec<String>,
}

fn first_line_about(raw: Option<&clap::builder::StyledStr>) -> String {
    raw.map(|s| {
        s.to_string()
            .lines()
            .next()
            .unwrap_or("")
            .trim()
            .to_owned()
    })
    .unwrap_or_default()
}

fn extract_opts(cmd: &clap::Command) -> (Vec<OptSpec>, Vec<String>) {
    let mut opts = Vec::new();
    let mut pos_values = Vec::new();
    for arg in cmd.get_arguments() {
        if arg.is_positional() {
            let pvals = arg
                .get_possible_values()
                .into_iter()
                .filter(|pv| !pv.is_hide_set())
                .map(|pv| pv.get_name().to_owned());
            pos_values.extend(pvals);
            continue;
        }
        let short = arg.get_short();
        let long = arg.get_long().map(str::to_owned);
        if short.is_none() && long.is_none() {
            continue;
        }
        opts.push(OptSpec {
            short,
            long,
            about: first_line_about(arg.get_help()),
        });
    }
    (opts, pos_values)
}

fn collect_cli_spec() -> (Vec<OptSpec>, Vec<CmdSpec>) {
    let root = crate::cli::cli_command();
    let (global_opts, _) = extract_opts(&root);
    let mut cmds = Vec::new();
    for sub in root.get_subcommands() {
        if sub.is_hide_set() || sub.get_name() == "help" {
            continue;
        }
        let (opts, pos_values) = extract_opts(sub);
        cmds.push(CmdSpec {
            name: sub.get_name().to_owned(),
            about: first_line_about(sub.get_about()),
            opts,
            pos_values,
        });
    }
    (global_opts, cmds)
}

fn format_flag_tokens(opts: &[OptSpec]) -> String {
    let mut tokens = BTreeSet::new();
    for o in opts {
        if let Some(s) = o.short {
            tokens.insert(format!("-{s}"));
        }
        if let Some(l) = &o.long {
            tokens.insert(format!("--{l}"));
        }
    }
    tokens.into_iter().collect::<Vec<_>>().join(" ")
}

/// Generate a completion script for `shell` from the active CLI definition.
pub fn generate(shell: ShellKind) -> String {
    let (global_opts, cmds) = collect_cli_spec();
    match shell {
        ShellKind::Bash => generate_bash(&global_opts, &cmds),
        ShellKind::Zsh => generate_zsh(&global_opts, &cmds),
        ShellKind::Fish => generate_fish(&global_opts, &cmds),
        ShellKind::PowerShell => generate_powershell(&global_opts, &cmds),
    }
}

fn generate_bash(global_opts: &[OptSpec], cmds: &[CmdSpec]) -> String {
    let cmd_names: String = cmds
        .iter()
        .map(|c| c.name.as_str())
        .collect::<Vec<_>>()
        .join(" ");
    let global_flags = format_flag_tokens(global_opts);

    let mut out = String::from(
        "# Bash completion for iris (generated by `iris completions bash`)\n\
         _iris_completions() {\n\
         \x20   local cur prev cmd\n\
         \x20   COMPREPLY=()\n\
         \x20   cur=\"${COMP_WORDS[COMP_CWORD]}\"\n\
         \x20   prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n\
         \x20   cmd=\"\"\n\
         \x20   local i=1\n\
         \x20   while [[ $i -lt $COMP_CWORD ]]; do\n\
         \x20       case \"${COMP_WORDS[$i]}\" in\n\
         \x20           -*)\n\
         \x20               ;;\n\
         \x20           *)\n\
         \x20               cmd=\"${COMP_WORDS[$i]}\"\n\
         \x20               break\n\
         \x20               ;;\n\
         \x20       esac\n\
         \x20       ((i++))\n\
         \x20   done\n\n\
         \x20   if [[ -z \"$cmd\" ]]; then\n\
         \x20       if [[ \"$cur\" == -* ]]; then\n",
    );
    let _ = writeln!(
        out,
        "            COMPREPLY=( $(compgen -W \"{global_flags} --help --version\" -- \"$cur\") )\n\
         \x20           return 0\n\
         \x20       fi\n\
         \x20       COMPREPLY=( $(compgen -W \"{cmd_names}\" -f -- \"$cur\") )\n\
         \x20       return 0\n\
         \x20   fi\n\n\
         \x20   case \"$cmd\" in"
    );

    for c in cmds {
        let mut all_flags = format_flag_tokens(&c.opts);
        if !all_flags.is_empty() && !global_flags.is_empty() {
            all_flags.push(' ');
        }
        all_flags.push_str(&global_flags);
        let pos_vals = c.pos_values.join(" ");
        let _ = writeln!(out, "        {})", c.name);
        let _ = writeln!(out, "            if [[ \"$cur\" == -* ]]; then");
        let _ = writeln!(
            out,
            "                COMPREPLY=( $(compgen -W \"{all_flags} --help\" -- \"$cur\") )"
        );
        let _ = writeln!(out, "                return 0");
        let _ = writeln!(out, "            fi");
        if !pos_vals.is_empty() {
            let _ = writeln!(
                out,
                "            COMPREPLY=( $(compgen -W \"{pos_vals}\" -- \"$cur\") )"
            );
            let _ = writeln!(out, "            return 0");
        }
        let _ = writeln!(out, "            ;;");
    }

    out.push_str(
        "    esac\n\
         }\n\
         complete -o default -F _iris_completions iris\n",
    );
    out
}

fn escape_zsh_sq(s: &str) -> String {
    s.replace('\'', "'\\''")
        .replace('[', "\\[")
        .replace(']', "\\]")
        .replace(':', "\\:")
}

fn generate_zsh(global_opts: &[OptSpec], cmds: &[CmdSpec]) -> String {
    let mut out = String::from(
        "#compdef iris\n\
         # Zsh completion for iris (generated by `iris completions zsh`)\n\n\
         _iris() {\n\
         \x20   local -a commands\n\
         \x20   commands=(\n",
    );
    for c in cmds {
        let desc = escape_zsh_sq(&c.about).replace("\\:", ":");
        let _ = writeln!(out, "        '{}:{}'", c.name, desc);
    }
    out.push_str(
        "    )\n\n\
         \x20   local context state state_descr line\n\
         \x20   _arguments -C \\\n",
    );
    for o in global_opts {
        let help = escape_zsh_sq(&o.about);
        if let Some(long) = &o.long {
            let _ = writeln!(out, "        '--{long}[{help}]' \\");
        }
    }
    out.push_str(
        "        '1:command:->cmds' \\\n\
         \x20       '*::arg:->args'\n\n\
         \x20   case \"$state\" in\n\
         \x20       cmds)\n\
         \x20           _describe 'command' commands\n\
         \x20           ;;\n\
         \x20       args)\n\
         \x20           case \"$line[1]\" in\n",
    );
    for c in cmds {
        let _ = writeln!(out, "                {})", c.name);
        let _ = writeln!(out, "                    _arguments \\");
        for o in &c.opts {
            let help = escape_zsh_sq(&o.about);
            if let Some(long) = &o.long {
                let _ = writeln!(out, "                        '--{long}[{help}]' \\");
            } else if let Some(short) = o.short {
                let _ = writeln!(out, "                        '-{short}[{help}]' \\");
            }
        }
        if !c.pos_values.is_empty() {
            let vals = c.pos_values.join(" ");
            let _ = writeln!(out, "                        '1:value:({vals})'");
        } else {
            let _ = writeln!(out, "                        '*:file:_files'");
        }
        let _ = writeln!(out, "                    ;;");
    }
    out.push_str(
        "            esac\n\
         \x20           ;;\n\
         \x20   esac\n\
         }\n\
         _iris \"$@\"\n",
    );
    out
}

fn escape_fish_dq(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('$', "\\$")
}

fn generate_fish(global_opts: &[OptSpec], cmds: &[CmdSpec]) -> String {
    let mut out =
        String::from("# Fish completion for iris (generated by `iris completions fish`)\n\n");
    for c in cmds {
        let desc = escape_fish_dq(&c.about);
        let _ = writeln!(
            out,
            "complete -c iris -f -n \"__fish_use_subcommand\" -a \"{}\" -d \"{desc}\"",
            c.name
        );
    }
    out.push('\n');
    for o in global_opts {
        let desc = escape_fish_dq(&o.about);
        let mut line = String::from("complete -c iris -n \"__fish_use_subcommand\"");
        if let Some(s) = o.short {
            let _ = write!(line, " -s {s}");
        }
        if let Some(l) = &o.long {
            let _ = write!(line, " -l {l}");
        }
        let _ = writeln!(line, " -d \"{desc}\"");
        out.push_str(&line);
    }
    out.push('\n');
    for c in cmds {
        for o in &c.opts {
            let desc = escape_fish_dq(&o.about);
            let mut line = format!("complete -c iris -n \"__fish_seen_subcommand_from {}\"", c.name);
            if let Some(s) = o.short {
                let _ = write!(line, " -s {s}");
            }
            if let Some(l) = &o.long {
                let _ = write!(line, " -l {l}");
            }
            let _ = writeln!(line, " -d \"{desc}\"");
            out.push_str(&line);
        }
        if !c.pos_values.is_empty() {
            let vals = c.pos_values.join(" ");
            let _ = writeln!(
                out,
                "complete -c iris -f -n \"__fish_seen_subcommand_from {}\" -a \"{vals}\"",
                c.name
            );
        }
    }
    out
}

fn escape_ps_sq(s: &str) -> String {
    s.replace('\'', "''")
}

fn generate_powershell(global_opts: &[OptSpec], cmds: &[CmdSpec]) -> String {
    let mut out = String::from(
        "# PowerShell completion for iris (generated by `iris completions powershell`)\n\
         Register-ArgumentCompleter -Native -CommandName @('iris', 'iris.exe') -ScriptBlock {\n\
         \x20   param($wordToComplete, $commandAst, $cursorPosition)\n\
         \x20   $tokens = @()\n\
         \x20   $elements = $commandAst.CommandElements\n\
         \x20   for ($i = 1; $i -lt $elements.Count; $i++) {\n\
         \x20       $t = $elements[$i].Extent.Text\n\
         \x20       if ($t -and -not $t.StartsWith('-')) { $tokens += $t }\n\
         \x20   }\n\
         \x20   $subcmd = if ($tokens.Count -gt 0 -and $tokens[0] -ne $wordToComplete) { $tokens[0] } else { '' }\n\n\
         \x20   $commands = @(\n",
    );
    for c in cmds {
        let tip = if c.about.is_empty() {
            c.name.clone()
        } else {
            escape_ps_sq(&c.about)
        };
        let _ = writeln!(out, "        @{{ Name = '{}'; Tip = '{}' }}", c.name, tip);
    }
    out.push_str("    )\n    $globalFlags = @(\n");
    for o in global_opts {
        let tip = if o.about.is_empty() {
            "option".to_owned()
        } else {
            escape_ps_sq(&o.about)
        };
        if let Some(l) = &o.long {
            let _ = writeln!(out, "        @{{ Name = '--{l}'; Tip = '{tip}' }}");
        }
        if let Some(s) = o.short {
            let _ = writeln!(out, "        @{{ Name = '-{s}'; Tip = '{tip}' }}");
        }
    }
    out.push_str("    )\n    $subFlags = @{\n");
    for c in cmds {
        let _ = writeln!(out, "        '{}' = @(", c.name);
        for o in &c.opts {
            let tip = if o.about.is_empty() {
                "option".to_owned()
            } else {
                escape_ps_sq(&o.about)
            };
            if let Some(l) = &o.long {
                let _ = writeln!(out, "            @{{ Name = '--{l}'; Tip = '{tip}' }}");
            }
            if let Some(s) = o.short {
                let _ = writeln!(out, "            @{{ Name = '-{s}'; Tip = '{tip}' }}");
            }
        }
        for pv in &c.pos_values {
            let _ = writeln!(out, "            @{{ Name = '{}'; Tip = '{}' }}", escape_ps_sq(pv), escape_ps_sq(pv));
        }
        out.push_str("        )\n");
    }
    out.push_str(
        "    }\n\n\
         \x20   $candidates = @()\n\
         \x20   if (-not $subcmd) {\n\
         \x20       if ($wordToComplete.StartsWith('-')) { $candidates = $globalFlags } else { $candidates = $commands }\n\
         \x20   } else {\n\
         \x20       if ($subFlags.ContainsKey($subcmd)) { $candidates += $subFlags[$subcmd] }\n\
         \x20       if ($wordToComplete.StartsWith('-')) { $candidates += $globalFlags }\n\
         \x20   }\n\n\
         \x20   $candidates |\n\
         \x20       Where-Object { $_.Name -like \"$wordToComplete*\" } |\n\
         \x20       ForEach-Object {\n\
         \x20           [System.Management.Automation.CompletionResult]::new($_.Name, $_.Name, 'ParameterValue', $_.Tip)\n\
         \x20       }\n\
         }\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_all_supported_shell_names() {
        assert_eq!(ShellKind::parse("bash").unwrap(), ShellKind::Bash);
        assert_eq!(ShellKind::parse("ZSH").unwrap(), ShellKind::Zsh);
        assert_eq!(ShellKind::parse("fish").unwrap(), ShellKind::Fish);
        assert_eq!(
            ShellKind::parse("powershell").unwrap(),
            ShellKind::PowerShell
        );
        assert_eq!(ShellKind::parse("pwsh").unwrap(), ShellKind::PowerShell);
        assert!(ShellKind::parse("tcsh").is_err());
    }

    #[test]
    fn generates_scripts_covering_core_commands_and_flags() {
        for (shell, marker) in [
            (ShellKind::Bash, "complete -o default -F _iris_completions iris"),
            (ShellKind::Zsh, "#compdef iris"),
            (ShellKind::Fish, "complete -c iris"),
            (ShellKind::PowerShell, "Register-ArgumentCompleter"),
        ] {
            let script = generate(shell);
            assert!(script.contains(marker), "{shell:?} missing {marker}");
            for cmd in ["build", "bundle", "doctor", "setup", "upgrade", "completions"] {
                assert!(script.contains(cmd), "{shell:?} missing command `{cmd}`");
            }
            for flag in ["--fix", "--full", "--gui", "--strict-effects"] {
                let needle = if shell == ShellKind::Fish {
                    format!("-l {}", flag.trim_start_matches("--"))
                } else {
                    flag.to_owned()
                };
                assert!(script.contains(&needle), "{shell:?} missing flag `{needle}`");
            }
        }
    }
}
